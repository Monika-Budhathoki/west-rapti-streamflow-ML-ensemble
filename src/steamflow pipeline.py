def build_lstm(n_features):
    """Small LSTM sized to the fixed feature count."""
    model = Sequential([
        Input(shape=(1, n_features)),
        LSTM(64, activation="tanh", return_sequences=False),
        Dropout(0.2),
        Dense(32, activation="relu"),
        Dense(1),
    ])
    model.compile(optimizer=Adam(learning_rate=0.001), loss="mse")
    return model


LSTM_SEED = 42  # single fixed seed


def _train_lstm_predict(X_tr_scaled, y_tr, X_predict_scaled, seed=LSTM_SEED):
    """Train a single LSTM on (X_tr_scaled, y_tr) with a fixed seed, then
    predict X_predict_scaled. Called once for Phase 1 (Train -> Val) and once
    for Phase 2 (Train+Val -> Test) - each call is a fresh refit."""
    n_feat = X_tr_scaled.shape[1]
    X_tr_lstm = X_tr_scaled.reshape((X_tr_scaled.shape[0], 1, n_feat))
    X_pred_lstm = X_predict_scaled.reshape((X_predict_scaled.shape[0], 1, n_feat))

    tf.random.set_seed(seed)
    np.random.seed(seed)

    lstm = build_lstm(n_feat)
    early_stop = EarlyStopping(
        monitor="val_loss", patience=8, restore_best_weights=True
    )
    lstm.fit(
        X_tr_lstm, y_tr,
        validation_split=0.15,
        epochs=50,
        batch_size=32,
        callbacks=[early_stop],
        verbose=0,
    )
    return lstm.predict(X_pred_lstm, verbose=0).flatten()


def _metrics_row(label, y_true, y_pred, prefix="Test"):
    return {
        "Model": label,
        f"{prefix}_R2": r2_score(y_true, y_pred),
        f"{prefix}_NSE": nse(y_true, y_pred),
        f"{prefix}_KGE": kge(y_true, y_pred),
        f"{prefix}_RMSE": np.sqrt(mean_squared_error(y_true, y_pred)),
        f"{prefix}_MAE": mean_absolute_error(y_true, y_pred),
    }


def _tie_breaker_rank(rows_df, kge_col, nse_col, r2_col, mae_col, rmse_col):
    """Tie-breaker sort: rounded KGE > rounded NSE > rounded R2 > MAE > RMSE."""
    ranking = rows_df.copy()
    ranking["_KGE_r"] = ranking[kge_col].round(2)
    ranking["_NSE_r"] = ranking[nse_col].round(2)
    ranking["_R2_r"] = ranking[r2_col].round(2)
    ranked = ranking.sort_values(
        by=["_KGE_r", "_NSE_r", "_R2_r", mae_col, rmse_col],
        ascending=[False, False, False, True, True],
    ).drop(columns=["_KGE_r", "_NSE_r", "_R2_r"]).reset_index(drop=True)
    return ranked


