# Method 3: Season-Specific Constrained-Weight Ensemble (SLSQP)
weight_bounds = [(0.0, 1.0), (0.0, 1.0)]
weight_sum_constraint = {"type": "eq", "fun": lambda w: np.sum(w) - 1.0}
initial_weights = np.array([0.5, 0.5])


def _monsoon_objective(w, p1, p2, y_true):
    blend = w[0] * p1 + w[1] * p2
    return -kge(y_true, blend)


def _dry_objective(w, p1, p2, y_true):
    blend = w[0] * p1 + w[1] * p2
    return mean_absolute_error(y_true, blend)


monsoon_result = minimize(
    _monsoon_objective, initial_weights,
    args=(pred1_monsoon, pred2_monsoon, y_monsoon_meta),
    method="SLSQP", bounds=weight_bounds, constraints=[weight_sum_constraint],
)
monsoon_weights = monsoon_result.x

dry_result = minimize(
    _dry_objective, initial_weights,
    args=(pred1_dry, pred2_dry, y_dry_meta),
    method="SLSQP", bounds=weight_bounds, constraints=[weight_sum_constraint],
)
dry_weights = dry_result.x

